package com.jme3.gde.unityscene;

import com.jme3.export.binary.BinaryExporter;
import com.jme3.gde.core.assets.ProjectAssetManager;
import com.jme3.scene.Node;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.function.Consumer;
import org.openide.filesystems.FileObject;
import org.openide.filesystems.FileUtil;

/** Writes a fresh scene bundle and project sources. Preview never invokes this export. */
final class UnityProjectExport {
    private static final Set<String> METADATA = Set.of("m_ObjectHideFlags",
            "m_CorrespondingSourceObject", "m_PrefabInstance", "m_PrefabAsset",
            "m_GameObject", "m_Enabled", "m_EditorHideFlags", "m_Script", "m_Name",
            "m_EditorClassIdentifier", "m_PrefabParentObject", "m_PrefabInternal");

    private final String bundle;
    private final Path sourceRoot;
    private final String packageName;
    private final Map<String, Node> prefabs = new LinkedHashMap<>();
    private final Map<String, String> scripts = new LinkedHashMap<>();
    private final Map<Path, String> javaSources = new LinkedHashMap<>();

    UnityProjectExport(String bundle, Path sourceRoot, String packageName) {
        this.bundle = bundle;
        this.sourceRoot = sourceRoot;
        this.packageName = packageName;
    }

    static boolean behaviourMetadata(String property) {
        return METADATA.contains(property);
    }

    String script(String guid, FileObject source, Consumer<String> warning) throws IOException {
        if (scripts.containsKey(guid)) {
            return scripts.get(guid);
        }
        String className = null;
        if (source == null || !"cs".equalsIgnoreCase(source.getExt())) {
            warning.accept("Missing C# source for script GUID " + guid);
        } else {
            try {
                String contents = source.asText("UTF-8");
                UnityScriptCompiler.Result result = UnityScriptCompiler.compile(
                        contents.startsWith("\uFEFF") ? contents.substring(1) : contents, packageName, guid);
                Path target = sourceRoot.resolve(result.className().replace('.', '/') + ".java");
                String marker = "// Generated by the JME Unity importer from GUID " + guid;
                String java = marker + "\n" + result.java();
                String existing = Files.exists(target) ? Files.readString(target) : null;
                if (existing != null && !existing.equals(java)) {
                    warning.accept("Preserved existing Java source: " + target
                            + ". Compare it with " + source.getPath() + " before regenerating this script.");
                    if (existing.lines().findFirst().orElse("").equals(marker)) {
                        className = result.className();
                    }
                } else {
                    className = result.className();
                    if (existing == null) {
                        javaSources.put(target, java);
                    }
                }
            } catch (IllegalArgumentException unsupported) {
                warning.accept(source.getPath() + ": " + unsupported.getMessage());
            }
        }
        scripts.put(guid, className);
        return className;
    }

    Node prefab(String guid) {
        return prefabs.get(guid.toLowerCase(Locale.ROOT));
    }

    void addPrefab(String guid, Node prefab) {
        prefabs.put(guid.toLowerCase(Locale.ROOT), prefab);
    }

    String prefabPath(String guid) {
        if (guid == null || !guid.matches("[0-9a-fA-F]{32}")) {
            throw new IllegalArgumentException("Invalid prefab GUID " + guid);
        }
        return bundle + "/Prefab-" + guid.toLowerCase(Locale.ROOT) + ".j3o";
    }

    static Path write(FileObject source, ProjectAssetManager assets, Path sourceRoot,
            String packageName) throws IOException {
        FileObject assetFolder = assets.getAssetFolder();
        Path directory = Files.createTempDirectory(FileUtil.toFile(assetFolder).toPath(), "UnityExport-");
        UnityProjectExport export = new UnityProjectExport(directory.getFileName().toString(), sourceRoot, packageName);
        List<Path> created = new ArrayList<>();
        created.add(directory);
        try {
            Node model = new UnitySceneLoader().load(source, assets, export);
            for (var entry : export.prefabs.entrySet()) {
                Path file = directory.resolve("Prefab-" + entry.getKey() + ".j3o");
                save(entry.getValue(), file, created);
            }
            Path result = directory.resolve(source.getName() + ".j3o");
            save(model, result, created);
            for (var entry : export.javaSources.entrySet()) {
                Path file = entry.getKey();
                Files.createDirectories(file.getParent());
                try (var writer = Files.newBufferedWriter(file, StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE)) {
                    created.add(file);
                    writer.write(entry.getValue());
                }
            }
            FileUtil.refreshFor(directory.toFile(), sourceRoot.toFile());
            return result;
        } catch (IOException | RuntimeException failure) {
            for (int i = created.size() - 1; i >= 0; i--) {
                try {
                    Files.deleteIfExists(created.get(i));
                } catch (IOException cleanup) {
                    failure.addSuppressed(cleanup);
                }
            }
            throw failure;
        }
    }

    private static void save(Node model, Path file, List<Path> created) throws IOException {
        try (var output = Files.newOutputStream(file, StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE)) {
            created.add(file);
            new BinaryExporter().save(model, output);
        }
    }
}
